const { contextBridge, ipcRenderer, webUtils } = require('electron');

contextBridge.exposeInMainWorld('board', {
  onSnapshot: (fn) => ipcRenderer.on('snapshot', (_e, data) => fn(data)),
  onTick: (fn) => ipcRenderer.on('tick', (_e, at) => fn(at)),
  onExpanded: (fn) => ipcRenderer.on('expanded', (_e, v, view) => fn(v, view)),
  onTestNode: (fn) => ipcRenderer.on('testnode', (_e, spec) => fn(spec)),
  onTestReopen: (fn) => ipcRenderer.on('testreopen', (_e, m) => fn(m)),
  onTestClick: (fn) => ipcRenderer.on('testclick', (_e, id) => fn(id)),
  onTestFocus: (fn) => ipcRenderer.on('testfocus', (_e, tty) => fn(tty)),
  onTestGrip: (fn) => ipcRenderer.on('testgrip', (_e, spec) => fn(spec || {})),
  onTestTrash: (fn) => ipcRenderer.on('testtrash', (_e, m) => fn(m)),
  onAutoAsk: (fn) => ipcRenderer.on('autoask', (_e, p) => fn(p)),
  onError: (fn) => ipcRenderer.on('error', (_e, m) => fn(m)),
  onChrome: (fn) => ipcRenderer.on('chrome', (_e, c) => fn(c)),
  toggle: (next) => ipcRenderer.invoke('toggle', next),
  moveBy: (dx, dy) => ipcRenderer.send('win-move-by', { dx, dy }),
  refresh: () => ipcRenderer.invoke('refresh'),
  copyResume: (s) => ipcRenderer.invoke('copy-resume', s),
  reveal: (s) => ipcRenderer.invoke('reveal', s),
  consult: (payload) => ipcRenderer.invoke('consult', payload),
  relay: (payload) => ipcRenderer.invoke('relay', payload),
  loadBoard: () => ipcRenderer.invoke('load-board'),
  saveBoard: (b) => ipcRenderer.invoke('save-board', b),
  setView: (name) => ipcRenderer.invoke('set-view', name),
  copyPeer: (name) => ipcRenderer.invoke('copy-peer', name),
  focusSession: (tty) => ipcRenderer.invoke('focus-session', tty),
  termAttach: (spec) => ipcRenderer.invoke('term-attach', spec),
  termInput: (data) => ipcRenderer.send('term-input', data),
  termResize: (cols, rows) => ipcRenderer.send('term-resize', { cols, rows }),
  termDetach: () => ipcRenderer.invoke('term-detach'),
  onTermData: (fn) => ipcRenderer.on('term-data', (_e, d) => fn(d)),
  onTermExit: (fn) => ipcRenderer.on('term-exit', (_e, name) => fn(name)),
  moveIntoBoard: (sessionId) => ipcRenderer.invoke('move-into-board', sessionId),
  // A dropped File no longer carries .path under context isolation; this is
  // the supported way to ask where it lives on disk.
  pathForFile: (file) => { try { return webUtils.getPathForFile(file); } catch { return ''; } },
  endSession: (p) => ipcRenderer.invoke('end-session', p),
  tileWindows: (ttys) => ipcRenderer.invoke('tile-windows', ttys),
  hideSessions: (keepSessionId) => ipcRenderer.invoke('hide-sessions', keepSessionId),
  showSessions: () => ipcRenderer.invoke('show-sessions'),
  sessionsAway: () => ipcRenderer.invoke('sessions-away'),
  openSessionWindow: (spec) => ipcRenderer.invoke('open-session-window', spec),
  handoff: (spec) => ipcRenderer.invoke('handoff', spec),
  usageSummary: (period) => ipcRenderer.invoke('usage-summary', period),
  onLimits: (fn) => ipcRenderer.on('limits', (_e, l) => fn(l)),
  refreshLimits: () => ipcRenderer.invoke('refresh-limits'),
  stow: () => ipcRenderer.invoke('stow'),
  setOnTop: (next) => ipcRenderer.invoke('set-on-top', next),
  quit: () => ipcRenderer.invoke('quit'),
});
